//1msごとの制御
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
	static uint32_t fb_tick = 0;

	if (htim == &htim7)
	{
		Origin_Reset_Process();		//原点リセットの要求があれば実行
		Encoder_Update();			//VESCの軸: エンコーダーから角度・位置・速度
		Read_LimitSwitch();			//リミットスイッチを読む

		for (int i = 0; i < MOTOR_NUM; i++)
		{
			if (mode[i] == POSITION)
			{
				Pos_P_control(i);
				if (!Motor_Use_Vesc_Rpm(i)) vel_PID_control(i);
			}
			else if (mode[i] == VELOCITY)
			{
				if (!Motor_Use_Vesc_Rpm(i)) vel_PID_control(i);
			}
			else if (mode[i] == GRIP)
			{
				Grip_Axis_Update(i);
			}
		}

		Limit_Switch_Apply();		//押されているスイッチの向きへは動かさない
		send_servo_data();			//サーボのPWMを更新

		send_motor_current_data();	//CAN2: モーターへ電流・RPM指令

		if (++fb_tick >= FB_TX_PERIOD_MS)
		{
			fb_tick = 0;
			for (int i = 0; i < MOTOR_NUM; i++)
			{
				send_feedback_data(i);	//CAN1: PCへフィードバック
			}
			send_limit_switch_data();
		}

		Frame_Count_Reset();

		CAN_Safe_Task(&hcan1);
		CAN_Safe_Task(&hcan2);
	}
}
